import math
def siiin(a):
    radians = 0
    radians = math.radians(a)
    a = math.sin(radians)
    return a
def cosinus(a):
    radians = 0
    radians = math.radians(a)
    a = math.cos(radians)
    return a
def tangens(a):
    radians = 0
    radians = math.radians(a)
    a = math.tan(radians)
    return a
def cotangens(a):
    radians = 0
    radians = math.radians(a)
    a = math.cos(radians) / math.sin(radians)
    return a
def sec(a):
    radians = 0
    radians = math.radians(a)
    a = 1 / math.cos(radians)
    return a
def cosec(a):
    radians = 0
    radians = math.radians(a)
    a = 1 / math.sin(radians)
    return a